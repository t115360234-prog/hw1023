#include <stdio.h>

int main(void) {
    int i, j, space;

    // ==========================================
    // (A) 靠左正三角形
    // 第一行 1 個 *，逐行增加到第 10 行 10 個 *
    // ==========================================
    printf("(A)\n");
    for (i = 1; i <= 10; i++) {
        for (j = 1; j <= i; j++) {
            printf("%s", "*"); // 題目要求的列印格式
        }
        printf("\n");
    }
    printf("\n");

    // ==========================================
    // (B) 靠左倒三角形
    // 第一行 10 個 *，逐行減少到第 10 行 1 個 *
    // ==========================================
    printf("(B)\n");
    for (i = 1; i <= 10; i++) {
        for (j = 1; j <= 11 - i; j++) {
            printf("%s", "*");
        }
        printf("\n");
    }
    printf("\n");

    // ==========================================
    // (C) 靠右倒三角形
    // 先印空格再印 *，* 數量從 10 逐行遞減到 1
    // ==========================================
    printf("(C)\n");
    for (i = 1; i <= 10; i++) {
        // 1. 印空格：第 i 行需要 (i - 1) 個空格
        for (space = 1; space <= i - 1; space++) {
            printf(" ");
        }
        // 2. 印星號：第 i 行需要 (11 - i) 個 *
        for (j = 1; j <= 11 - i; j++) {
            printf("%s", "*");
        }
        printf("\n");
    }
    printf("\n");

    // ==========================================
    // (D) 靠右正三角形
    // 先印空格再印 *，* 數量從 1 逐行遞增到 10
    // ==========================================
    printf("(D)\n");
    for (i = 1; i <= 10; i++) {
        // 1. 印空格：第 i 行需要 (10 - i) 個空格
        for (space = 1; space <= 10 - i; space++) {
            printf(" ");
        }
        // 2. 印星號：第 i 行需要 i 個 *
        for (j = 1; j <= i; j++) {
            printf("%s", "*");
        }
        printf("\n");
    }

    return 0;
}